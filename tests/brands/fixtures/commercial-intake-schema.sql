create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create function public.has_role(text) returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.user_roles where user_id=auth.uid() and role::text=$1)$$;
create function public.is_master_or_admin()returns boolean language sql stable as $$select public.has_role('master')or public.has_role('admin')$$;
create function public.is_admin()returns boolean language sql stable as $$select public.has_role('admin')$$;
create function public.is_current_active_advisor_v1(uuid)returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.profiles p join public.user_roles r on r.user_id=p.id where p.id=$1 and p.is_active and r.role='advisor')$$;
