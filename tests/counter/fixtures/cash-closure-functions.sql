CREATE OR REPLACE FUNCTION app_private.void_account_closure_v1(p_closure_id bigint, p_reason text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_uid uuid:=auth.uid(); v_closure public.money_account_closures%rowtype; v_now timestamptz:=statement_timestamp(); v_ids bigint[]; v_item_ids bigint[];
begin
  if v_uid is null or not exists(select 1 from public.user_roles where user_id=v_uid and role='admin') then
    raise exception 'Solo Admin puede anular cierres.' using errcode='42501';
  end if;
  p_reason:=btrim(regexp_replace(coalesce(p_reason,''),'\s+',' ','g'));
  if length(p_reason) not between 6 and 500 then raise exception 'Indica un motivo claro para anular el cierre.' using errcode='22023'; end if;
  select * into v_closure from public.money_account_closures where id=p_closure_id;
  if not found then raise exception 'Cierre no encontrado.' using errcode='22023'; end if;
  perform id from public.money_accounts where id=v_closure.money_account_id or id in
    (select money_account_id from public.money_movements where reference_code='closure-'||p_closure_id) order by id for update;
  select * into v_closure from public.money_account_closures where id=p_closure_id for update;
  if exists(select 1 from public.account_closure_reversals where closure_id=p_closure_id) and v_closure.status='rejected' then
    return jsonb_build_object('closureId',p_closure_id,'replayed',true);
  end if;
  if v_closure.status not in ('recorded','approved') then raise exception 'El cierre ya no está activo.' using errcode='22023'; end if;
  if exists(select 1 from public.money_account_closures where money_account_id=v_closure.money_account_id
    and status in ('recorded','approved') and closure_at>v_closure.closure_at) then
    raise exception 'Hay cierres posteriores que dependen de este saldo. Revisa primero el último cierre.' using errcode='22023';
  end if;
  perform id from public.money_account_reconciliation_items where source_kind='closure' and source_id=p_closure_id order by id for update;
  if exists(select 1 from public.money_account_reconciliation_items where source_kind='closure' and source_id=p_closure_id and status='resolved') then
    raise exception 'Este cierre tiene una diferencia ya resuelta; revisa su resolución antes de anularlo.' using errcode='22023';
  end if;
  -- Legacy close transfers retain the existing exact reference convention. This
  -- does not certify description-based historical links as new evidence.
  with changed as (update public.money_movements set status='voided',reviewed_at=v_now,reviewed_by_user_id=v_uid,
    voided_at=v_now,voided_by_user_id=v_uid,void_reason='Cierre anulado: '||p_reason
    where reference_code='closure-'||p_closure_id and status<>'voided' returning id)
  select array_agg(id order by id) into v_ids from changed;
  with changed as (update public.money_account_reconciliation_items set status='voided',voided_at=v_now,voided_by_user_id=v_uid,void_reason=p_reason
    where source_kind='closure' and source_id=p_closure_id and status='open' returning id)
  select array_agg(id order by id) into v_item_ids from changed;
  update public.money_account_closures set status='rejected',reviewed_at=v_now,reviewed_by_user_id=v_uid,
    notes=concat_ws(E'\n',nullif(btrim(notes),''),'Anulado: '||p_reason) where id=p_closure_id;
  insert into public.account_closure_reversals(closure_id,created_by,reason,snapshot)
  values(p_closure_id,v_uid,p_reason,jsonb_build_object('previous',to_jsonb(v_closure),'movementIds',coalesce(v_ids,'{}'::bigint[]),
    'reconciliationItemIds',coalesce(v_item_ids,'{}'::bigint[])));
  return jsonb_build_object('closureId',p_closure_id,'replayed',false);
end;
$function$
;

CREATE OR REPLACE FUNCTION public.counter_close_money_account(p_idempotency_key uuid, p_money_account_id bigint, p_closure_at timestamp with time zone, p_counted_amount numeric, p_exchange_rate_ves_per_usd numeric DEFAULT NULL::numeric, p_reason text DEFAULT NULL::text, p_notes text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_uid uuid := (select auth.uid());
  v_is_supervisor boolean;
  v_claim record;
  v_receipt_id bigint;
  v_request_payload jsonb;
  v_result jsonb;
  v_account record;
  v_profile record;
  v_previous_closure record;
  v_baseline record;
  v_anchor_at timestamptz;
  v_closure_date date;
  v_counted_amount numeric(12,2);
  v_counted_usd numeric(12,2);
  v_expected_amount numeric(12,2);
  v_expected_usd numeric(12,2);
  v_difference_amount numeric(12,2);
  v_difference_usd numeric(12,2);
  v_rate numeric(18,6);
  v_closure_id bigint;
  v_is_pos_closure boolean;
begin
  if v_uid is null then
    raise exception 'Not authenticated';
  end if;

  v_is_supervisor := public.is_master_or_admin();
  if not v_is_supervisor and not public.has_role('counter') then
    raise exception 'Only Counter or Master/Admin can close a Counter money account';
  end if;

  if p_closure_at is null then
    raise exception 'closure_at is required';
  end if;

  if p_counted_amount is null or p_counted_amount < 0 then
    raise exception 'counted_amount must be >= 0';
  end if;

  if nullif(btrim(p_reason), '') is null then
    raise exception 'Closure reason is required';
  end if;

  v_request_payload := jsonb_build_object(
    'money_account_id', p_money_account_id,
    'closure_at', p_closure_at,
    'counted_amount', p_counted_amount,
    'exchange_rate_ves_per_usd', p_exchange_rate_ves_per_usd,
    'reason', p_reason,
    'notes', p_notes
  );

  select *
  into v_claim
  from public.counter_claim_command(
    p_idempotency_key,
    'close_money_account',
    null,
    p_money_account_id,
    v_request_payload
  );

  if v_claim.existing_result is not null then
    return v_claim.existing_result;
  end if;
  v_receipt_id := v_claim.receipt_id;

  select account.*
  into v_account
  from public.money_accounts account
  where account.id = p_money_account_id
  for update;

  if not found or not v_account.is_active then
    raise exception 'Money account is missing or inactive';
  end if;

  if not v_is_supervisor and not public.is_counter_direct_money_account(p_money_account_id) then
    raise exception 'Counter can only close an active direct Counter account';
  end if;

  select
    profile.closure_kind,
    profile.requires_zero_difference,
    profile.allows_classified_difference,
    profile.baseline_required
  into v_profile
  from public.money_account_closure_profiles profile
  where profile.money_account_id = p_money_account_id;

  if not found then
    raise exception 'Money account has no closure profile';
  end if;
  v_is_pos_closure := v_account.account_kind::text = 'pos' or v_profile.closure_kind::text = 'pos';

  v_closure_date := (p_closure_at at time zone 'America/Caracas')::date;
  v_counted_amount := round(p_counted_amount, 2);
  v_rate := case
    when v_account.currency_code = 'VES'
      then round(p_exchange_rate_ves_per_usd, 6)
    else null
  end;

  if v_account.currency_code = 'VES'
     and (v_rate is null or v_rate <= 0) then
    raise exception 'A valid exchange rate is required to close a VES account';
  end if;

  v_counted_usd := case
    when v_counted_amount = 0 then 0
    else public.counter_amount_usd(v_account.currency_code, v_counted_amount, v_rate)
  end;

  if exists (
    select 1
    from public.money_account_closures closure
    where closure.money_account_id = p_money_account_id
      and closure.closure_at = p_closure_at
      and closure.status in ('recorded', 'approved')
  ) then
    raise exception 'An active closure already exists for this account and timestamp';
  end if;

  select
    closure.id,
    closure.closure_at,
    closure.counted_amount,
    closure.counted_amount_usd
  into v_previous_closure
  from public.money_account_closures closure
  where closure.money_account_id = p_money_account_id
    and closure.status in ('recorded', 'approved')
    and closure.closure_at < p_closure_at
  order by closure.closure_at desc, closure.created_at desc, closure.id desc
  limit 1;

  if found then
    v_anchor_at := v_previous_closure.closure_at;
    v_expected_amount := case
      when v_is_pos_closure then 0
      else round(v_previous_closure.counted_amount, 2)
    end;
    v_expected_usd := case
      when v_is_pos_closure then 0
      else round(v_previous_closure.counted_amount_usd, 2)
    end;
  else
    select
      baseline.id,
      baseline.baseline_at,
      baseline.counted_amount,
      baseline.counted_amount_usd
    into v_baseline
    from public.money_account_closure_baselines baseline
    where baseline.money_account_id = p_money_account_id
      and baseline.status = 'active'
      and baseline.baseline_at <= p_closure_at
    order by baseline.baseline_at desc, baseline.created_at desc, baseline.id desc
    limit 1;

    if not found then
      if v_profile.baseline_required then
        raise exception 'Money account requires a baseline before its first closure';
      end if;
      v_anchor_at := '-infinity'::timestamptz;
      v_expected_amount := 0;
      v_expected_usd := 0;
    else
      v_anchor_at := v_baseline.baseline_at;
      v_expected_amount := case
        when v_is_pos_closure then 0
        else round(v_baseline.counted_amount, 2)
      end;
      v_expected_usd := case
        when v_is_pos_closure then 0
        else round(v_baseline.counted_amount_usd, 2)
      end;
    end if;
  end if;

  select
    round(
      v_expected_amount
      + coalesce(sum(
        case
          when v_is_pos_closure
           and movement.direction = 'outflow'
           and movement.movement_type = 'withdrawal'
           and settled_closure.id is not null
            then 0
          when movement.direction = 'inflow' then movement.amount
          else -movement.amount
        end
      ), 0),
      2
    ),
    round(
      v_expected_usd
      + coalesce(sum(
        case
          when v_is_pos_closure
           and movement.direction = 'outflow'
           and movement.movement_type = 'withdrawal'
           and settled_closure.id is not null
            then 0
          when movement.direction = 'inflow' then movement.amount_usd_equivalent
          else -movement.amount_usd_equivalent
        end
      ), 0),
      2
    )
  into v_expected_amount, v_expected_usd
  from public.money_movements movement
  left join public.money_account_closures settled_closure
    on v_is_pos_closure
   and movement.direction = 'outflow'
   and movement.movement_type = 'withdrawal'
   and movement.reference_code ~ '^closure-[0-9]+$'
   and settled_closure.id = substring(movement.reference_code from '^closure-([0-9]+)$')::bigint
   and settled_closure.money_account_id = p_money_account_id
   and settled_closure.status in ('recorded', 'approved')
  where movement.money_account_id = p_money_account_id
    and movement.status = 'confirmed'
    and movement.movement_date <= v_closure_date
    and coalesce(movement.confirmed_at, movement.created_at) > v_anchor_at
    and coalesce(movement.confirmed_at, movement.created_at) <= p_closure_at;

  v_difference_amount := round(v_counted_amount - v_expected_amount, 2);
  v_difference_usd := round(v_counted_usd - v_expected_usd, 2);

  if v_profile.requires_zero_difference
     and abs(v_difference_amount) > 0.009 then
    raise exception
      'This account requires zero difference; counted %, expected %, difference %. Record an adjustment before closing',
      v_counted_amount,
      v_expected_amount,
      v_difference_amount;
  end if;

  insert into public.money_account_closures (
    money_account_id,
    closure_date,
    closure_at,
    expected_amount,
    counted_amount,
    difference_amount,
    expected_amount_usd,
    counted_amount_usd,
    difference_amount_usd,
    currency_code,
    exchange_rate_ves_per_usd,
    reason,
    notes,
    status,
    created_by_user_id
  ) values (
    p_money_account_id,
    v_closure_date,
    p_closure_at,
    v_expected_amount,
    v_counted_amount,
    v_difference_amount,
    v_expected_usd,
    v_counted_usd,
    v_difference_usd,
    v_account.currency_code,
    v_rate,
    format('Counter - %s', btrim(p_reason)),
    nullif(btrim(p_notes), ''),
    'recorded',
    v_uid
  )
  returning id into v_closure_id;

  if v_profile.allows_classified_difference
     and abs(v_difference_amount) > 0.009 then
    insert into public.money_account_reconciliation_items (
      money_account_id,
      source_kind,
      source_id,
      item_type,
      direction,
      currency_code,
      amount,
      amount_usd_equivalent,
      operation_date,
      reference_code,
      counterparty_name,
      description,
      status,
      created_by_user_id
    ) values (
      p_money_account_id,
      'closure',
      v_closure_id,
      'other_pending',
      case when v_difference_amount > 0 then 'surplus' else 'shortage' end,
      v_account.currency_code::text,
      abs(v_difference_amount),
      abs(v_difference_usd),
      v_closure_date,
      format('closure-%s', v_closure_id),
      null,
      case
        when v_difference_amount > 0
          then format('Excedente pendiente por identificar en cierre de %s', v_account.name)
        else format('Faltante pendiente por explicar en cierre de %s', v_account.name)
      end,
      'open',
      v_uid
    );
  end if;

  v_result := jsonb_build_object(
    'ok', true,
    'closure_id', v_closure_id,
    'money_account_id', p_money_account_id,
    'closure_at', p_closure_at,
    'closure_date', v_closure_date,
    'expected_amount', v_expected_amount,
    'counted_amount', v_counted_amount,
    'difference_amount', v_difference_amount,
    'currency_code', v_account.currency_code,
    'expected_amount_usd', v_expected_usd,
    'counted_amount_usd', v_counted_usd,
    'difference_amount_usd', v_difference_usd
  );

  return public.counter_complete_command(v_receipt_id, v_result);
end;
$function$
;

CREATE OR REPLACE FUNCTION public.counter_read_cash_snapshot(p_movement_limit integer DEFAULT 12)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_limit integer := least(greatest(coalesce(p_movement_limit, 12), 1), 25);
  v_today date := (now() at time zone 'America/Caracas')::date;
  v_payload jsonb;
begin
  if (select auth.uid()) is null
     or not (
       public.has_role('counter')
       or public.is_master_or_admin()
     ) then
    raise exception 'counter_access_denied' using errcode = '42501';
  end if;

  with allowed_accounts as materialized (
    select
      account.id,
      account.name,
      account.account_kind::text as account_kind,
      account.currency_code::text as currency_code,
      profile.closure_kind,
      profile.baseline_required,
      array_agg(
        distinct rule.payment_method_code
        order by rule.payment_method_code
      ) filter (where rule.payment_method_code is not null) as methods
    from public.money_accounts account
    join public.money_account_payment_rules rule
      on rule.money_account_id = account.id
    left join public.money_account_closure_profiles profile
      on profile.money_account_id = account.id
    where public.is_counter_direct_money_account(account.id)
      and rule.role::text = 'counter'
      and rule.is_active = true
      and (
        coalesce(rule.can_confirm_payment, false)
        or coalesce(rule.auto_confirms_report, false)
      )
    group by
      account.id,
      account.name,
      account.account_kind,
      account.currency_code,
      profile.closure_kind,
      profile.baseline_required
  ),
  anchors as materialized (
    select
      allowed.*,
      closure_row.id as closure_id,
      closure_row.closure_date,
      closure_row.closure_at,
      closure_row.created_at as closure_created_at,
      closure_row.expected_amount as closure_expected_amount,
      closure_row.counted_amount as closure_counted_amount,
      closure_row.difference_amount as closure_difference_amount,
      closure_creator.full_name as closure_created_by_name,
      baseline_row.baseline_date,
      baseline_row.baseline_at,
      baseline_row.counted_amount as baseline_amount
    from allowed_accounts allowed
    left join lateral (
      select
        closure.id,
        closure.closure_date,
        coalesce(closure.closure_at, closure.created_at) as closure_at,
        closure.created_at,
        closure.expected_amount,
        closure.counted_amount,
        closure.difference_amount,
        closure.created_by_user_id
      from public.money_account_closures closure
      where closure.money_account_id = allowed.id
        and closure.status in ('recorded', 'approved')
      order by
        closure.closure_at desc nulls last,
        closure.created_at desc,
        closure.id desc
      limit 1
    ) closure_row on true
    left join public.profiles closure_creator
      on closure_creator.id = closure_row.created_by_user_id
    left join lateral (
      select
        baseline.baseline_date,
        baseline.baseline_at,
        baseline.counted_amount
      from public.money_account_closure_baselines baseline
      where baseline.money_account_id = allowed.id
        and baseline.status = 'active'
      order by baseline.baseline_at desc, baseline.id desc
      limit 1
    ) baseline_row on closure_row.id is null
  ),
  balances as materialized (
    select
      anchor.id,
      round((
        case
          when anchor.account_kind = 'pos' then 0
          else coalesce(anchor.closure_counted_amount, anchor.baseline_amount, 0)
        end
        + coalesce(sum(
          case
            when anchor.account_kind = 'pos'
             and movement.direction::text = 'outflow'
             and movement.movement_type::text = 'withdrawal'
             and settled_closure.id is not null
              then 0
            when movement.direction::text = 'inflow' then movement.amount
            else -movement.amount
          end
        ), 0)
      )::numeric, 2) as balance
    from anchors anchor
    left join public.money_movements movement
      on movement.money_account_id = anchor.id
     and movement.status::text = 'confirmed'
     and movement.movement_date <= v_today
     and (
       case
         when anchor.closure_id is not null then
           movement.movement_date > anchor.closure_date
           or (
             movement.movement_date = anchor.closure_date
             and coalesce(movement.confirmed_at, movement.created_at) > anchor.closure_at
           )
         when anchor.baseline_date is not null then
           movement.movement_date > anchor.baseline_date
           or (
             movement.movement_date = anchor.baseline_date
             and coalesce(movement.confirmed_at, movement.created_at) > anchor.baseline_at
           )
         else true
       end
     )
    left join public.money_account_closures settled_closure
      on anchor.account_kind = 'pos'
     and movement.direction::text = 'outflow'
     and movement.movement_type::text = 'withdrawal'
     and movement.reference_code ~ '^closure-[0-9]+$'
     and settled_closure.id = substring(movement.reference_code from '^closure-([0-9]+)$')::bigint
     and settled_closure.money_account_id = anchor.id
     and settled_closure.status in ('recorded', 'approved')
    group by
      anchor.id,
      anchor.account_kind,
      anchor.closure_id,
      anchor.closure_date,
      anchor.closure_at,
      anchor.closure_counted_amount,
      anchor.baseline_date,
      anchor.baseline_at,
      anchor.baseline_amount
  ),
  today_totals as materialized (
    select
      allowed.id,
      round(coalesce(sum(movement.amount) filter (
        where movement.direction::text = 'inflow'
      ), 0)::numeric, 2) as inflow,
      round(coalesce(sum(movement.amount) filter (
        where movement.direction::text = 'outflow'
      ), 0)::numeric, 2) as outflow,
      count(movement.id) as movement_count
    from allowed_accounts allowed
    left join public.money_movements movement
      on movement.money_account_id = allowed.id
     and movement.status::text = 'confirmed'
     and movement.movement_date = v_today
    group by allowed.id
  ),
  shaped as (
    select
      anchor.account_kind,
      anchor.name,
      anchor.id,
      jsonb_build_object(
        'accountId', anchor.id,
        'accountName', coalesce(
          nullif(trim(anchor.name), ''),
          'Cuenta ' || anchor.id::text
        ),
        'accountKind', anchor.account_kind,
        'closureKind', anchor.closure_kind,
        'currencyCode', anchor.currency_code,
        'methods', coalesce(to_jsonb(anchor.methods), '[]'::jsonb),
        'inflow', coalesce(totals.inflow, 0),
        'outflow', coalesce(totals.outflow, 0),
        'net', round((
          coalesce(totals.inflow, 0) - coalesce(totals.outflow, 0)
        )::numeric, 2),
        'balance', coalesce(balance.balance, 0),
        'closureExpectedAmount', coalesce(balance.balance, 0),
        'closureReady',
          (
            anchor.closure_id is not null
            or anchor.baseline_date is not null
            or not coalesce(anchor.baseline_required, false)
          )
          and coalesce(balance.balance, 0) >= 0,
        'movementCount', coalesce(totals.movement_count, 0),
        'lastClosure',
          case
            when anchor.closure_id is null then null
            else jsonb_build_object(
              'id', anchor.closure_id,
              'closureAt', anchor.closure_at,
              'expectedAmount', anchor.closure_expected_amount,
              'countedAmount', anchor.closure_counted_amount,
              'differenceAmount', anchor.closure_difference_amount,
              'createdByName', nullif(trim(anchor.closure_created_by_name), '')
            )
          end,
        'pendingRequestCount', (
          select count(*)
          from public.money_movements pending
          where pending.money_account_id = anchor.id
            and pending.status::text = 'pending'
            and pending.approval_required = true
            and pending.movement_type::text = 'expense_payment'
            and pending.order_id is null
        ),
        'pendingRequests', coalesce((
          select jsonb_agg(
            request.payload
            order by request.created_at desc, request.id desc
          )
          from (
            select
              pending.created_at,
              pending.id,
              jsonb_build_object(
                'id', pending.id,
                'movementGroupId', pending.movement_group_id,
                'movementDate', pending.movement_date,
                'createdAt', pending.created_at,
                'amount', pending.amount,
                'amountUsdEquivalent', pending.amount_usd_equivalent,
                'currencyCode', pending.currency_code::text,
                'referenceCode', pending.reference_code,
                'counterpartyName', pending.counterparty_name,
                'description', pending.description,
                'approvalReason', pending.approval_required_reason,
                'createdByName', nullif(trim(creator.full_name), '')
              ) as payload
            from public.money_movements pending
            left join public.profiles creator
              on creator.id = pending.created_by_user_id
            where pending.money_account_id = anchor.id
              and pending.status::text = 'pending'
              and pending.approval_required = true
              and pending.movement_type::text = 'expense_payment'
              and pending.order_id is null
            order by pending.created_at desc, pending.id desc
            limit 8
          ) request
        ), '[]'::jsonb),
        'movements', coalesce((
          select jsonb_agg(
            recent.payload
            order by recent.created_at desc, recent.id desc
          )
          from (
            select
              movement.created_at,
              movement.id,
              jsonb_build_object(
                'id', movement.id,
                'movementDate', movement.movement_date,
                'createdAt', movement.created_at,
                'direction', movement.direction::text,
                'movementType', movement.movement_type::text,
                'amount', movement.amount,
                'amountUsdEquivalent', movement.amount_usd_equivalent,
                'currencyCode', movement.currency_code::text,
                'referenceCode', movement.reference_code,
                'counterpartyName', movement.counterparty_name,
                'description', movement.description,
                'orderId', movement.order_id,
                'createdByName', nullif(trim(creator.full_name), '')
              ) as payload
            from public.money_movements movement
            left join public.profiles creator
              on creator.id = movement.created_by_user_id
            where movement.money_account_id = anchor.id
              and movement.status::text = 'confirmed'
              and movement.movement_date = v_today
            order by movement.created_at desc, movement.id desc
            limit v_limit
          ) recent
        ), '[]'::jsonb)
      ) as payload
    from anchors anchor
    join balances balance on balance.id = anchor.id
    join today_totals totals on totals.id = anchor.id
  )
  select coalesce(
    jsonb_agg(
      shaped.payload
      order by
        case shaped.account_kind when 'cash' then 1 when 'pos' then 2 else 3 end,
        shaped.name,
        shaped.id
    ),
    '[]'::jsonb
  )
  into v_payload
  from shaped;

  return v_payload;
end;
$function$
;

CREATE OR REPLACE FUNCTION app_private.account_movement_in_observed_cut_v2(p_date date, p_recorded_at timestamp with time zone, p_anchor_at timestamp with time zone, p_cut_at timestamp with time zone)
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  select p_date <= (p_cut_at at time zone 'America/Caracas')::date
    and p_recorded_at <= p_cut_at
    and (p_anchor_at is null or (
      p_date >= (p_anchor_at at time zone 'America/Caracas')::date
      and p_recorded_at > p_anchor_at
    ));
$function$
;

CREATE OR REPLACE FUNCTION app_private.account_closure_cut_v2(p_account_id bigint, p_at timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$
declare
  a public.money_accounts%rowtype;
  p public.money_account_closure_profiles%rowtype;
  b public.money_account_closure_baselines%rowtype;
  c public.money_account_closures%rowtype;
  anchor_at timestamptz;
  pos boolean;
  expected numeric;
  expected_usd numeric;
  movements jsonb;
begin
  if p_at is null or not isfinite(p_at) then raise exception 'Fecha y hora inválidas.' using errcode='22023'; end if;
  select * into a from public.money_accounts where id=p_account_id;
  if not found then raise exception 'Cuenta no encontrada.' using errcode='22023'; end if;
  select * into p from public.money_account_closure_profiles where money_account_id=a.id;
  select * into c from public.money_account_closures
    where money_account_id=a.id and status in ('recorded','approved')
      and coalesce(closure_at,created_at)<p_at
    order by coalesce(closure_at,created_at) desc,created_at desc,id desc limit 1;
  select * into b from public.money_account_closure_baselines
    where money_account_id=a.id and status='active' and baseline_at<p_at
    order by baseline_at desc,id desc limit 1;
  anchor_at:=coalesce(c.closure_at,c.created_at,b.baseline_at);
  pos:=a.account_kind::text='pos' or coalesce(p.closure_kind,'')='pos';
  select round(coalesce(sum(case when m.direction='inflow' then app_private.reconciled_observed_amount_v1(m.id,m.amount,anchor_at,p_at) else -app_private.reconciled_observed_amount_v1(m.id,m.amount,anchor_at,p_at) end),0),2),
    round(coalesce(sum(case when m.direction='inflow' then app_private.reconciled_observed_amount_v1(m.id,m.amount_usd_equivalent,anchor_at,p_at,true) else -app_private.reconciled_observed_amount_v1(m.id,m.amount_usd_equivalent,anchor_at,p_at,true) end),0),2),
    coalesce(jsonb_agg(jsonb_build_object('id',m.id,'direction',m.direction,'type',m.movement_type,'amount',m.amount,
      'usd',m.amount_usd_equivalent,'date',m.movement_date,'recordedAt',coalesce(m.confirmed_at,m.created_at)) order by m.id),'[]')
  into expected,expected_usd,movements from public.money_movements m
  where m.money_account_id=a.id and m.status='confirmed'
    and app_private.account_movement_in_observed_cut_v2(m.movement_date,coalesce(m.confirmed_at,m.created_at),anchor_at,p_at)
    and not(pos and m.direction='outflow' and m.movement_type='withdrawal' and exists(
      select 1 from public.money_account_closures s where s.money_account_id=a.id and s.status in ('recorded','approved')
        and coalesce(s.closure_at,s.created_at)<=p_at and m.reference_code='closure-'||s.id::text));
  if not pos then
    expected:=expected+coalesce(c.counted_amount,b.counted_amount,0);
    expected_usd:=expected_usd+coalesce(c.counted_amount_usd,b.counted_amount_usd,0);
  end if;
  return jsonb_build_object('moneyAccountId',a.id,'currencyCode',a.currency_code,'closureAt',p_at,
    'closureDate',(p_at at time zone 'America/Caracas')::date,'expectedAmount',expected,'expectedAmountUsd',expected_usd,
    'previousClosure',to_jsonb(c),'baseline',to_jsonb(b),'movements',movements);
end;
$function$
;

