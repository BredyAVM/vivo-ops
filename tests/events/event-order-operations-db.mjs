  assert.deepEqual(await query('select id from order_items where order_id=$1', [order.id]), item);
  assert.deepEqual(await query('select * from payment_reports'), payments); assert.deepEqual(await query('select * from commission_closures'), closures);
  assert.equal((await query('select count(*) n from inventory_movements'))[0].n, 0);
