insert into public.inventory_alert_policies (
  alert_category,
  inventory_item_id,
  is_enabled
)
select category_name, null, true
from unnest(array[
  'availability',
  'commitment',
  'production',
  'control',
  'procurement',
  'system'
]::text[]) as category(category_name);

