-- Block 13A: canonical inventory alert structure.
--
-- Inventory alerts are deliberately separate from order notifications and the
-- Master inbox. Policies describe which roles receive each alert category and
-- on which surface. Alert rows preserve one operational episode at a time.

set lock_timeout = '5s';
set statement_timeout = '60s';

create table public.inventory_alert_policies (
  id bigint generated by default as identity primary key,
  alert_category text not null,
  inventory_item_id bigint,
  is_enabled boolean not null default true,
  created_by_user_id uuid,
  updated_by_user_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint inventory_alert_policies_category_check
    check (alert_category in (
      'availability',
      'commitment',
      'production',
      'control',
      'procurement',
      'system'
    )),
  constraint inventory_alert_policies_inventory_item_id_fkey
    foreign key (inventory_item_id)
    references public.inventory_items(id)
    on delete cascade,
  constraint inventory_alert_policies_created_by_user_id_fkey
    foreign key (created_by_user_id)
    references public.profiles(id)
    on delete set null,
  constraint inventory_alert_policies_updated_by_user_id_fkey
    foreign key (updated_by_user_id)
    references public.profiles(id)
    on delete set null
);

create unique index inventory_alert_policies_global_category_uidx
  on public.inventory_alert_policies (alert_category)
  where inventory_item_id is null;

create unique index inventory_alert_policies_item_category_uidx
  on public.inventory_alert_policies (inventory_item_id, alert_category)
  where inventory_item_id is not null;

create index inventory_alert_policies_inventory_item_id_idx
  on public.inventory_alert_policies (inventory_item_id)
  where inventory_item_id is not null;

create index inventory_alert_policies_created_by_user_id_idx
  on public.inventory_alert_policies (created_by_user_id)
  where created_by_user_id is not null;

create index inventory_alert_policies_updated_by_user_id_idx
  on public.inventory_alert_policies (updated_by_user_id)
  where updated_by_user_id is not null;

create table public.inventory_alert_policy_routes (
  id bigint generated by default as identity primary key,
  inventory_alert_policy_id bigint not null,
  target_role public.user_role not null,
  surface text not null,
  created_at timestamptz not null default now(),
  constraint inventory_alert_policy_routes_policy_id_fkey
    foreign key (inventory_alert_policy_id)
    references public.inventory_alert_policies(id)
    on delete cascade,
  constraint inventory_alert_policy_routes_surface_check
    check (surface in (
      'inventory_center',
      'advisor_availability',
      'master_inventory',
      'kitchen_inventory',
      'counter_inventory',
      'admin_inventory'
    )),
  constraint inventory_alert_policy_routes_role_surface_check
    check (
      (surface = 'inventory_center' and target_role in ('admin', 'master'))
      or (surface = 'advisor_availability' and target_role = 'advisor')
      or (surface = 'master_inventory' and target_role = 'master')
      or (surface = 'kitchen_inventory' and target_role = 'kitchen')
      or (surface = 'counter_inventory' and target_role = 'counter')
      or (surface = 'admin_inventory' and target_role = 'admin')
    )
);

create unique index inventory_alert_policy_routes_route_uidx
  on public.inventory_alert_policy_routes (
    inventory_alert_policy_id,
    target_role,
    surface
  );

create index inventory_alert_policy_routes_role_surface_policy_idx
  on public.inventory_alert_policy_routes (
    target_role,
    surface,
    inventory_alert_policy_id
  );

create table public.inventory_alerts (
  id bigint generated by default as identity primary key,
  alert_key text not null,
  alert_category text not null,
  alert_type text not null,
  severity text not null,
  requires_action boolean not null default false,
  status text not null default 'open',
  inventory_item_id bigint,
  order_id bigint,
  planned_flow_id bigint,
  inventory_count_id bigint,
  order_timeline_event_id bigint,
  title text not null,
  message text,
  details jsonb not null default '{}'::jsonb,
  first_detected_at timestamptz not null default now(),
  last_detected_at timestamptz not null default now(),
  managed_by_user_id uuid,
  managed_at timestamptz,
  resolved_by_user_id uuid,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint inventory_alerts_key_not_blank_check
    check (btrim(alert_key) <> '' and char_length(alert_key) <= 240),
  constraint inventory_alerts_category_check
    check (alert_category in (
      'availability',
      'commitment',
      'production',
      'control',
      'procurement',
      'system'
    )),
  constraint inventory_alerts_type_not_blank_check
    check (btrim(alert_type) <> '' and char_length(alert_type) <= 120),
  constraint inventory_alerts_severity_check
    check (severity in ('info', 'warning', 'critical')),
  constraint inventory_alerts_status_check
    check (status in ('open', 'managed', 'resolved')),
  constraint inventory_alerts_title_not_blank_check
    check (btrim(title) <> '' and char_length(title) <= 240),
  constraint inventory_alerts_message_length_check
    check (message is null or char_length(message) <= 2000),
  constraint inventory_alerts_details_object_check
    check (jsonb_typeof(details) = 'object'),
  constraint inventory_alerts_detection_time_check
    check (last_detected_at >= first_detected_at),
  constraint inventory_alerts_management_audit_check
    check (
      (managed_at is null and managed_by_user_id is null)
      or (managed_at is not null and managed_by_user_id is not null)
    ),
  constraint inventory_alerts_resolution_audit_check
    check (
      (resolved_at is null and resolved_by_user_id is null)
      or resolved_at is not null
    ),
  constraint inventory_alerts_status_audit_check
    check (
      (status = 'open' and resolved_at is null and resolved_by_user_id is null)
      or (
        status = 'managed'
        and managed_at is not null
        and managed_by_user_id is not null
        and resolved_at is null
        and resolved_by_user_id is null
      )
      or (status = 'resolved' and resolved_at is not null)
    ),
  constraint inventory_alerts_inventory_item_id_fkey
    foreign key (inventory_item_id)
    references public.inventory_items(id)
    on delete set null,
  constraint inventory_alerts_order_id_fkey
    foreign key (order_id)
    references public.orders(id)
    on delete set null,
  constraint inventory_alerts_planned_flow_id_fkey
    foreign key (planned_flow_id)
    references public.inventory_planned_flows(id)
    on delete set null,
  constraint inventory_alerts_inventory_count_id_fkey
    foreign key (inventory_count_id)
    references public.inventory_counts(id)
    on delete set null,
  constraint inventory_alerts_order_timeline_event_id_fkey
    foreign key (order_timeline_event_id)
    references public.order_timeline_events(id)
    on delete set null,
  constraint inventory_alerts_managed_by_user_id_fkey
    foreign key (managed_by_user_id)
    references public.profiles(id)
    on delete set null,
  constraint inventory_alerts_resolved_by_user_id_fkey
    foreign key (resolved_by_user_id)
    references public.profiles(id)
    on delete set null
);

