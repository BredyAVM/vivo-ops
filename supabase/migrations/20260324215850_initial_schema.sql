 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid UUID;
  v_status payment_report_status;
BEGIN
  IF NOT public.is_master_or_admin() THEN
