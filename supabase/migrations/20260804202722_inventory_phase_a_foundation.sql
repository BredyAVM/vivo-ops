alter table public.inventory_items
  add constraint inventory_items_tracking_mode_check
    check (
      tracking_mode is null
      or tracking_mode in ('transactional', 'periodic_count', 'not_tracked')
    ),
  add constraint inventory_items_consumption_triggers_check
    check (
      consumption_triggers is null
      or (
        consumption_triggers <@ array['sale', 'production', 'manual_issue']::text[]
        and array_position(consumption_triggers, null) is null
      )
    ),
  add constraint inventory_items_availability_mode_check
    check (
      availability_mode is null
      or availability_mode in ('on_hand_only', 'immediate_recipe', 'scheduled_recipe')
    ),
  add constraint inventory_items_target_stock_units_check
    check (target_stock_units is null or target_stock_units >= 0),
  add constraint inventory_items_shelf_life_days_check
    check (shelf_life_days is null or shelf_life_days >= 0),
  add constraint inventory_items_primary_count_frequency_check
    check (
      primary_count_frequency is null
      or primary_count_frequency in ('per_shift', 'daily', 'weekly', 'biweekly', 'monthly')
    ),
  add constraint inventory_items_merged_into_not_self_check
    check (merged_into_item_id is null or merged_into_item_id <> id),
  add constraint inventory_items_merged_into_item_id_fkey
    foreign key (merged_into_item_id)
    references public.inventory_items(id)
    on delete restrict;

