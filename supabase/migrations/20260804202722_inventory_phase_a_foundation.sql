create table public.inventory_count_lines (
  id bigint generated by default as identity primary key,
  inventory_count_id bigint not null,
  inventory_item_id bigint not null,
  expected_quantity_units numeric not null,
  counted_quantity_units numeric,
  difference_quantity_units numeric generated always as (
    counted_quantity_units - expected_quantity_units
  ) stored,
  line_status text not null default 'pending'::text,
  note text,
  movement_id bigint,
  recounted_from_line_id bigint,
  counted_by_user_id uuid,
  counted_at timestamp with time zone,
  reviewed_by_user_id uuid,
  reviewed_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  constraint inventory_count_lines_inventory_count_id_fkey
    foreign key (inventory_count_id)
    references public.inventory_counts(id)
    on delete cascade,
  constraint inventory_count_lines_inventory_item_id_fkey
    foreign key (inventory_item_id)
    references public.inventory_items(id)
    on delete restrict,
  constraint inventory_count_lines_movement_id_fkey
    foreign key (movement_id)
    references public.inventory_movements(id)
    on delete restrict,
  constraint inventory_count_lines_recounted_from_line_id_fkey
    foreign key (recounted_from_line_id)
    references public.inventory_count_lines(id)
    on delete restrict,
  constraint inventory_count_lines_counted_by_user_id_fkey
    foreign key (counted_by_user_id)
    references public.profiles(id)
    on delete restrict,
  constraint inventory_count_lines_reviewed_by_user_id_fkey
    foreign key (reviewed_by_user_id)
    references public.profiles(id)
    on delete restrict,
  constraint inventory_count_lines_count_item_key
    unique (inventory_count_id, inventory_item_id),
  constraint inventory_count_lines_counted_nonnegative_check
    check (counted_quantity_units is null or counted_quantity_units >= 0),
  constraint inventory_count_lines_status_check
    check (line_status in (
      'pending',
      'submitted',
      'accepted',
      'recount_requested',
      'superseded'
    )),
  constraint inventory_count_lines_recount_not_self_check
    check (recounted_from_line_id is null or recounted_from_line_id <> id),
  constraint inventory_count_lines_counted_audit_check
    check (
      (counted_quantity_units is null and counted_by_user_id is null and counted_at is null)
      or (counted_quantity_units is not null and counted_by_user_id is not null and counted_at is not null)
    ),
  constraint inventory_count_lines_review_audit_check
    check (
      (reviewed_at is null and reviewed_by_user_id is null)
      or (reviewed_at is not null and reviewed_by_user_id is not null)
    )
);

