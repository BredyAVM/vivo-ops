create or replace function public.counter_direct_sale_item_notes(
  p_product_id bigint,
  p_qty numeric,
  p_item_note text,
  p_detail_lines jsonb
)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_product public.products%rowtype;
  v_component record;
  v_line text;
  v_alias text;
  v_component_id bigint;
  v_component_qty numeric;
  v_counted_units numeric := 0;
  v_detail text := nullif(trim(coalesce(p_item_note, '')), '');
  v_seen_component_ids bigint[] := array[]::bigint[];
  v_selected_component_ids bigint[] := array[]::bigint[];
  v_selected_component_qty numeric[] := array[]::numeric[];
  v_index integer;
begin
  select *
  into v_product
  from public.products
  where id = p_product_id
    and is_active = true;

  if not found then
    raise exception 'counter_product_unavailable';
  end if;

  if p_qty is null or p_qty <= 0 or p_qty > 999 then
    raise exception 'counter_item_quantity_invalid';
  end if;

  if length(coalesce(p_item_note, '')) > 500 then
    raise exception 'counter_item_note_too_long';
  end if;

  if p_detail_lines is null then
    p_detail_lines := '[]'::jsonb;
  end if;
  if jsonb_typeof(p_detail_lines) <> 'array' then
    raise exception 'counter_item_detail_invalid';
  end if;
  if jsonb_array_length(p_detail_lines) > 100 then
    raise exception 'counter_item_detail_too_long';
  end if;

  if v_product.is_detail_editable then
    if p_qty <> 1 then
      raise exception 'counter_configurable_product_quantity_must_be_one';
    end if;

    for v_line in
      select trim(value)
      from jsonb_array_elements_text(p_detail_lines)
    loop
      if v_line = '' then
        continue;
      end if;

      if v_line ~* '^para\s*:' then
        v_alias := nullif(trim(regexp_replace(v_line, '^para\s*:\s*', '', 'i')), '');
        if length(coalesce(v_alias, '')) > 120 then
          raise exception 'counter_item_alias_too_long';
        end if;
        continue;
      end if;

      if left(v_line, 5) <> '@sel|' then
        continue;
      end if;

      if v_line !~ '^@sel\|[0-9]+\|[0-9]+(\.[0-9]+)?$' then
        raise exception 'counter_item_selection_invalid';
      end if;

      v_component_id := split_part(v_line, '|', 2)::bigint;
      v_component_qty := split_part(v_line, '|', 3)::numeric;

      if v_component_qty <= 0
         or v_component_qty <> trunc(v_component_qty)
         or v_component_id = any(v_seen_component_ids) then
        raise exception 'counter_item_selection_invalid';
      end if;

      select
        pc.component_product_id,
        pc.component_mode,
        pc.quantity,
        pc.counts_toward_detail_limit,
        pc.is_required,
        pc.sort_order,
        component.name as component_name
      into v_component
      from public.product_components pc
      join public.products component
        on component.id = pc.component_product_id
       and component.is_active = true
      where pc.parent_product_id = p_product_id
        and pc.component_product_id = v_component_id;

      if not found then
        raise exception 'counter_item_component_unavailable';
      end if;

      if v_component.component_mode = 'fixed'
         and v_component_qty <> v_component.quantity then
        raise exception 'counter_item_fixed_component_quantity_invalid';
      end if;

      v_seen_component_ids := array_append(v_seen_component_ids, v_component_id);
      v_selected_component_ids := array_append(v_selected_component_ids, v_component_id);
      v_selected_component_qty := array_append(v_selected_component_qty, v_component_qty);

      if v_component.counts_toward_detail_limit then
        v_counted_units := v_counted_units + v_component_qty;
      end if;
    end loop;

    if exists (
      select 1
      from public.product_components pc
      where pc.parent_product_id = p_product_id
        and pc.component_mode = 'fixed'
        and pc.is_required = true
        and not (pc.component_product_id = any(v_seen_component_ids))
    ) then
      raise exception 'counter_item_required_component_missing';
    end if;

    if v_product.detail_units_limit > 0
       and v_counted_units <> v_product.detail_units_limit then
      raise exception 'counter_item_detail_limit_mismatch';
    end if;

    if v_alias is not null then
      v_detail := concat_ws(E'\n', v_detail, 'Para: ' || v_alias);
    end if;

    for v_component in
      select
        pc.component_product_id,
        pc.sort_order,
        component.name as component_name
      from public.product_components pc
      join public.products component
        on component.id = pc.component_product_id
      where pc.parent_product_id = p_product_id
        and pc.component_product_id = any(v_selected_component_ids)
      order by pc.sort_order, component.name, pc.id
    loop
      v_index := array_position(v_selected_component_ids, v_component.component_product_id);
      v_component_qty := v_selected_component_qty[v_index];
      v_detail := concat_ws(E'\n', v_detail, v_component_qty::text || ' ' || v_component.component_name);
      v_detail := concat_ws(
        E'\n',
        v_detail,
        '@sel|' || v_component.component_product_id::text || '|' || v_component_qty::text
      );
    end loop;
  else
    for v_component in
      select
        pc.quantity,
        pc.sort_order,
        component.name as component_name
      from public.product_components pc
      join public.products component
        on component.id = pc.component_product_id
       and component.is_active = true
      where pc.parent_product_id = p_product_id
        and pc.component_mode = 'fixed'
        and pc.is_required = true
      order by pc.sort_order, component.name, pc.id
    loop
      v_detail := concat_ws(
        E'\n',
        v_detail,
        (v_component.quantity * p_qty)::text || ' ' || v_component.component_name
      );
    end loop;
  end if;

  return nullif(v_detail, '');
end;
$function$;

revoke all on function public.counter_direct_sale_item_notes(bigint, numeric, text, jsonb)
  from public, anon, authenticated;
grant execute on function public.counter_direct_sale_item_notes(bigint, numeric, text, jsonb)
  to service_role;

create or replace function public.trg_order_items_set_pricing()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  v_product record;
  v_unit_price numeric;
  v_is_counter_direct_sale boolean := false;
  v_fx_rate numeric;
begin
  if new.override_unit_price_usd is not null
     or new.override_reason is not null
     or new.override_approved_by is not null
     or new.override_approved_at is not null then
    if not public.is_admin() then
      raise exception 'Only ADMIN can change item pricing or set an override.';
    end if;
  end if;

  select
    p.id,
    p.sku,
    p.name,
    p.base_price_usd,
    p.base_price_bs,
    p.source_price_currency,
    p.source_price_amount,
    coalesce(o.extra_fields #>> '{counter,quick_sale}', 'false') = 'true' as is_counter_direct_sale,
    case
      when coalesce(o.extra_fields #>> '{counter,quick_sale}', 'false') = 'true'
        then nullif(o.extra_fields #>> '{pricing,fx_rate}', '')::numeric
      else null
    end as fx_rate
  into v_product
  from public.products p
  join public.orders o on o.id = new.order_id
  where p.id = new.product_id;

  if not found then
    raise exception 'Invalid product_id';
  end if;

  v_is_counter_direct_sale := v_product.is_counter_direct_sale;
  v_fx_rate := v_product.fx_rate;

  if tg_op = 'INSERT' then
    new.sku_snapshot := v_product.sku;
    new.product_name_snapshot := v_product.name;

    if v_is_counter_direct_sale then
      if v_fx_rate is null or v_fx_rate <= 0 then
        raise exception 'counter_exchange_rate_invalid';
      end if;

      new.pricing_origin_currency := v_product.source_price_currency::text;
      new.pricing_origin_amount := v_product.source_price_amount;

      if v_product.source_price_currency::text = 'VES' then
        new.unit_price_bs_snapshot := round(v_product.source_price_amount, 2);
        new.line_total_bs_snapshot := round(v_product.source_price_amount * coalesce(new.qty, 0), 2);
        new.unit_price_usd_snapshot := round(v_product.source_price_amount / v_fx_rate, 2);
        new.line_total_usd := round(v_product.source_price_amount * coalesce(new.qty, 0) / v_fx_rate, 2);
      else
        new.unit_price_usd_snapshot := round(v_product.source_price_amount, 2);
        new.line_total_usd := round(v_product.source_price_amount * coalesce(new.qty, 0), 2);
        new.unit_price_bs_snapshot := round(v_product.source_price_amount * v_fx_rate, 2);
        new.line_total_bs_snapshot := round(v_product.source_price_amount * coalesce(new.qty, 0) * v_fx_rate, 2);
      end if;

      return new;
    end if;

    new.unit_price_usd_snapshot := v_product.base_price_usd;
  end if;

  v_unit_price := coalesce(new.override_unit_price_usd, new.unit_price_usd_snapshot);
  new.line_total_usd := coalesce(new.qty, 0) * coalesce(v_unit_price, 0);
  return new;
end;
$function$;

create or replace function public.counter_read_catalog()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_payload jsonb;
begin
  if (select auth.uid()) is null
     or not (
       public.has_role('counter')
       or public.is_master_or_admin()
     ) then
    raise exception 'counter_access_denied' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'products',
      coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', p.id,
            'sku', p.sku,
            'name', coalesce(nullif(trim(p.name), ''), 'Producto'),
            'type', p.type::text,
            'sourcePriceCurrency', coalesce(p.source_price_currency::text, 'USD'),
            'sourcePriceAmount', coalesce(p.source_price_amount, 0),
            'basePriceUsd', coalesce(p.base_price_usd, 0),
            'basePriceBs', coalesce(p.base_price_bs, 0),
            'unitsPerService', coalesce(p.units_per_service, 0),
            'isDetailEditable', coalesce(p.is_detail_editable, false),
            'detailUnitsLimit', coalesce(p.detail_units_limit, 0),
            'isComboComponentSelectable', coalesce(p.is_combo_component_selectable, false)
          )
          order by p.name, p.id
        )
        from public.products p
        where p.is_active = true
      ), '[]'::jsonb),
    'components',
      coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', pc.id,
            'parentProductId', pc.parent_product_id,
            'componentProductId', pc.component_product_id,
            'componentMode', pc.component_mode::text,
            'quantity', coalesce(pc.quantity, 0),
            'countsTowardDetailLimit', coalesce(pc.counts_toward_detail_limit, false),
            'isRequired', coalesce(pc.is_required, false),
            'sortOrder', coalesce(pc.sort_order, 0),
            'notes', pc.notes,
            'parentSku', parent.sku,
            'parentName', parent.name,
            'componentSku', component.sku,
            'componentName', coalesce(nullif(trim(component.name), ''), 'Componente'),
            'componentType', component.type::text
          )
          order by pc.parent_product_id, pc.sort_order, pc.id
        )
        from public.product_components pc
        join public.products parent
          on parent.id = pc.parent_product_id
         and parent.is_active = true
        join public.products component
          on component.id = pc.component_product_id
         and component.is_active = true
      ), '[]'::jsonb),
    'discountRules',
      coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', rule.id,
            'code', rule.code,
            'name', rule.name,
            'description', rule.description,
            'discountPct', rule.discount_pct,
            'paymentMethodCodes', to_jsonb(rule.payment_method_codes),
            'paymentCurrencies', to_jsonb(rule.payment_currencies),
            'fulfillments', to_jsonb(rule.fulfillments),
            'startsAt', rule.starts_at,
            'endsAt', rule.ends_at
          )
          order by rule.discount_pct, rule.name, rule.id
        )
        from public.order_discount_rules rule
        where rule.is_active = true
          and 'counter'::public.user_role = any(rule.eligible_roles)
          and (rule.starts_at is null or rule.starts_at <= now())
          and (rule.ends_at is null or rule.ends_at > now())
      ), '[]'::jsonb)
  )
  into v_payload;

  return v_payload;
end;
$function$;

