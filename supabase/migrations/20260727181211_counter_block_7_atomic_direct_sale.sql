begin;

create table if not exists public.order_discount_rules (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text,
  discount_pct numeric(9,4) not null,
  eligible_roles public.user_role[] not null default array[]::public.user_role[],
  payment_method_codes text[] not null default array[]::text[],
  payment_currencies public.currency_code[] not null default array[]::public.currency_code[],
  fulfillments public.fulfillment_type[] not null default array[]::public.fulfillment_type[],
  starts_at timestamptz,
  ends_at timestamptz,
  is_active boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint order_discount_rules_code_ck
    check (code = upper(code) and code ~ '^[A-Z0-9][A-Z0-9_-]{1,39}$'),
  constraint order_discount_rules_name_ck
    check (length(trim(name)) between 2 and 120),
  constraint order_discount_rules_pct_ck
    check (discount_pct > 0 and discount_pct <= 100),
  constraint order_discount_rules_roles_ck
    check (cardinality(eligible_roles) > 0),
  constraint order_discount_rules_window_ck
    check (ends_at is null or starts_at is null or ends_at > starts_at)
);

create index if not exists order_discount_rules_counter_active_idx
  on public.order_discount_rules (starts_at, ends_at, id)
  where is_active = true and 'counter'::public.user_role = any (eligible_roles);

