create or replace function public.counter_normalize_phone(p_phone text)
returns text
language plpgsql
immutable
strict
set search_path = ''
as $function$
declare
  v_raw text := trim(p_phone);
  v_digits text;
  v_explicit boolean;
  v_result text;
begin
  v_explicit := v_raw ~ '^\s*(\+|00)';
  v_digits := regexp_replace(v_raw, '[^0-9]', '', 'g');

  if v_digits = '' then
    return null;
  end if;

  if v_explicit then
    if left(v_digits, 2) = '00' then
      v_digits := substring(v_digits from 3);
    end if;
    v_result := '+' || v_digits;
  elsif left(v_digits, 2) = '58' and length(v_digits) >= 11 then
    v_result := '+' || v_digits;
  elsif left(v_digits, 1) = '0' and length(v_digits) >= 10 then
    v_result := '+58' || substring(v_digits from 2);
  elsif length(v_digits) between 9 and 10 then
    v_result := '+58' || v_digits;
  else
    return null;
  end if;

  if v_result !~ '^\+[1-9][0-9]{6,14}$' then
    return null;
  end if;

  return v_result;
end;
$function$;

revoke all on function public.counter_normalize_phone(text) from public, anon;
grant execute on function public.counter_normalize_phone(text) to authenticated, service_role;

